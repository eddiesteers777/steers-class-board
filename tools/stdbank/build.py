"""Build the standards Question Bank: data/stdbank/<course>.js from tools/stdbank/<course>.py.

    python3 tools/stdbank/build.py

Each course file holds problems written for one set of Alabama standards. Every code and part letter is checked
against data/standards.js (built from Eddie's Alabama curriculum docs); a code that is not there stops the build.
Answers are computed from the same numbers that write each question wherever the math allows it.
"""
import importlib, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

COURSES = [  # module, output, class it is written for, label
    ("g7", "g7", "7th", "7th Grade"),
    ("g8", "g8", "8th", "8th Grade"),
    ("alg1", "alg1", "8th-acc", "Algebra I (8th Accelerated)"),
]


def standards():
    js = "import('" + os.path.join(ROOT, "data/standards.js").replace("\\", "/") + "').then(m=>console.log(JSON.stringify(m.STANDARDS)))"
    return json.loads(subprocess.check_output(["node", "-e", js]))


def main():
    S = standards()
    codes = {}
    for cls, c in S.items():
        for s in c["standards"]:
            codes.setdefault(s["code"], set(p["l"] for p in s["parts"]))
    total = 0
    for mod, outname, cls, label in COURSES:
        try:
            m = importlib.import_module(mod)
        except ModuleNotFoundError:
            continue
        items, seen, count = [], set(), {}
        for x in m.out:
            std = x["std"]
            if std not in codes:
                sys.exit("Unknown standard %s in %s: %s" % (std, mod, x["q"]))
            if std not in [s["code"] for s in S[cls]["standards"]]:
                sys.exit("%s is not a %s standard: %s" % (std, cls, x["q"]))
            if x.get("part") and x["part"] not in codes[std]:
                sys.exit("%s has no part %s: %s" % (std, x["part"], x["q"]))
            key = re.sub(r"\s+", " ", x["q"].lower()).strip()
            if key in seen:
                sys.exit("Same question twice: " + x["q"])
            seen.add(key)
            if not str(x["a"]).strip():
                sys.exit("No answer: " + x["q"])
            if x.get("choices") and x["a"] not in x["choices"]:
                sys.exit("Answer is not one of the choices: " + x["q"])
            if "$" in x["q"] + x["a"]:
                sys.exit("Use § for a dollar sign: " + x["q"])
            count[std] = count.get(std, 0) + 1
            o = {"id": "%s-%02d" % (std.replace(" ", ""), count[std])}
            o.update(x)
            items.append(o)
        missing = [s["code"] for s in S[cls]["standards"] if s["code"] not in count and (cls != "8th-acc" or s["code"].startswith("Alg"))]
        path = os.path.join(ROOT, "data/stdbank", outname + ".js")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write("// Standards Question Bank: %s. GENERATED by tools/stdbank/build.py from tools/stdbank/%s.py.\n" % (label, mod))
            f.write("// Do not hand-edit; change the .py file and build again. Standards codes are checked against data/standards.js.\n")
            f.write("// Fields: id, std (Alabama code), part (letter), q, a, lvl (1 on-ramp, 2 on level, 3 stretch), choices, also (other right answers).\n")
            f.write("export default " + json.dumps({"cls": cls, "label": label, "items": items}, ensure_ascii=False, indent=0).replace("\n", "") + ";\n")
        total += len(items)
        print("%-5s %4d problems, %d standards%s" % (mod, len(items), len(count), ("; no problems yet for " + ", ".join(missing)) if missing else ""))
    print("total", total)


if __name__ == "__main__":
    main()
