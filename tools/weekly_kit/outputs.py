"""Things generated from the week file that are text, not Word files."""
import json
from datetime import date, timedelta
from weekfile import DAYS, to_board, to_plain

BOARD_DAY = ("name", "title", "date", "agendaLine", "short", "bell", "agenda", "supplies", "reminders", "lt")


def board_week(week):
    """The public, student-facing subset for the board site (data/weekN.js)."""
    out = {k: week[k] for k in ("id", "label", "dates", "monday")}
    out["classes"] = {}
    for cid, c in week["classes"].items():
        k = {"label": c["label"], "cls": c["cls"], "weekLT": c["weekLT"], "bellSeconds": c.get("bellSeconds", 300), "days": []}
        for d in c["days"]:
            day = {f: d.get(f, [] if f in ("agenda", "supplies", "reminders") else "") for f in BOARD_DAY}
            day["title"] = d.get("title") or d["name"]
            day["problems"] = [{"q": to_board(p["q"]), "a": to_board(p["a"])} for p in d.get("problems") or []]
            if d.get("notes"): day["notes"] = board_notes(d["notes"])
            k["days"].append(day)
        if c.get("speed"): k["speed"] = c["speed"]
        k["links"] = c.get("links") or []
        out["classes"][cid] = k
    return out


def board_notes(n):
    """Guided notes for the board's step-by-step screen. Exit ticket answers are left out."""
    b = to_board; out = {"title": n["title"]}
    if n.get("targets"): out["targets"] = [b(t) for t in n["targets"]]
    if n.get("warmup"): out["warmup"] = [{"q": b(p["q"]), "a": b(p["a"])} for p in n["warmup"]]
    if n.get("vocab"): out["vocab"] = {"items": [b(v) for v in n["vocab"]["items"]]}
    if n.get("bigIdea"): out["bigIdea"] = [b(t) for t in n["bigIdea"]]
    if n.get("steps"): out["steps"] = [b(t) for t in n["steps"]]
    if n.get("examples"):
        out["examples"] = []
        for e in n["examples"]:
            x = {"title": e.get("title", ""), "q": b(e["q"]), "steps": [{"m": b(st["m"]), "why": b(st.get("why", ""))} for st in e["steps"]]}
            if e.get("intro"): x["intro"] = [b(t) for t in e["intro"]]
            out["examples"].append(x)
    if n.get("guided"): out["guided"] = {"q": b(n["guided"]["q"]), "steps": [{"m": b(x.get("full") or x["m"]), "why": b(x.get("why", ""))} for x in n["guided"]["steps"]]}
    if n.get("practice"):
        out["practice"] = []
        for part in n["practice"]:
            # "showWork" parts (problems worked together) also send the worked line to the board
            probs = [dict({"n": p.get("n", ""), "q": b(p["q"]), "a": b(p["a"])}, **({"work": b(p["work"])} if part.get("showWork") and p.get("work") else {})) for p in part["problems"]]
            item = {"label": part.get("label", ""), "problems": probs}
            if part.get("kind"): item["kind"] = part["kind"]
            out["practice"].append(item)
    if n.get("exit"): out["exit"] = [{"q": b(p["q"])} for p in n["exit"]]
    return out


def board_js(week):
    head = ("// Calera Math — %s (%s).\n// GENERATED by tools/weekly_kit/build_week.py from the week file. Do not edit by hand:\n"
            "// change the week file and build again. Student-facing content only.\nexport default ") % (week["label"], week["dates"])
    return head + json.dumps(board_week(week), ensure_ascii=False, indent=1) + ";\n"


def _md(d):
    return "%d/%d" % (d.month, d.day)


def parent_message(week, cid):
    """The weekly Thrillshare message, in Eddie's standing format, built only from the week file."""
    c = week["classes"][cid]; mon = date.fromisoformat(week["monday"])
    lines = ["Hello %s families," % c.get("greeting", c["label"].lower()), ""]
    lines += ["This week we are %s." % c["topic"].rstrip("."), ""] if c.get("topic") else []
    a = c.get("assessment") or {}
    if a.get("type") in ("quiz", "test"):
        when = mon + timedelta(days=DAYS.index(a["day"]))
        lines += ["%s: %s %s." % (a.get("name") or a["type"].capitalize(), a["day"], _md(when)), ""]
    for i, d in enumerate(c["days"]):
        lines.append("%s %s: %s" % (DAYS[i][:3], _md(mon + timedelta(days=i)), to_plain(d.get("parent") or d["agendaLine"])))
    lines.append("")
    if c.get("homeworkLine"): lines += [to_plain(c["homeworkLine"]), ""]
    if c.get("agendaUrl"): lines += ["Full weekly agenda with all materials: " + c["agendaUrl"], ""]
    if week.get("contactEmail"): lines += ["Questions? Email %s." % week["contactEmail"], ""]
    lines.append("Thank you, Mr. Steers")
    return "\n".join(lines)


def slide_text(week, cid):
    """Text for each slide box (Weekly Agenda slide + five day slides), as a readable table."""
    c = week["classes"][cid]
    wk = "\n".join("%s: %s" % (DAYS[i][:3], d["short"]) for i, d in enumerate(c["days"]))
    out = ["# %s — %s slide text" % (c["label"], week["label"]), "", "## Weekly Agenda slide",
           "Week line: %s  |  %s" % (week["label"], week["dates"])]
    out += ["%s: %s" % (d["name"], to_plain(d["agendaLine"])) for d in c["days"]]
    out += ["Learning target: " + to_plain(c["weekLT"]), ""]
    for d in c["days"]:
        out += ["## %s" % (d.get("title") or d["name"]), "Date: " + d["date"], "Bell ringer: " + to_plain(d["bell"]),
                "Agenda: " + " / ".join(to_plain(x) for x in d["agenda"]), "Supplies: " + " / ".join(d["supplies"]),
                "Reminders: " + " / ".join(d.get("reminders") or []), "Learning target: " + to_plain(d["lt"]), "This Week:", wk, ""]
    return "\n".join(out)
